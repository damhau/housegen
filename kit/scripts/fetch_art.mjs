// The kit's wall art (#102): the archviz spike's prints (spikes/archviz/made/art: museum works in the public domain,
// prints made there) as kit/art.js and kit/assets/art/<id>.webp (512 px on the long side; the photo service frames
// the full-resolution file of the same id). Each print's frame and mount are the spike's (artlib.py _dress): by its
// kind, one per series. Prints darker than DARK, or tagged with no style, are left out.
// Run from kit/: node scripts/fetch_art.mjs
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const KIT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(KIT, "..", "spikes", "archviz", "made", "art");
const DARK = 0.3;
const DRESS = {
  japanese: [["black", "oak", "ash"], 0.11],
  botanical: [["oak", "white", "brass", "ash"], 0.1],
  abstract: [["black", "white", "oak"], 0.08],
  drawing: [["white", "oak", "ash"], 0.12],
  landscape: [["white", "oak", "black"], 0.1],
  interior: [["black", "oak"], 0.08],
  photo: [["black", "white"], 0.13],
  stilllife: [["oak", "black"], 0],
  painting: [["oak", "black", "ash"], 0],
  gen: [["oak", "black", "ash"], null],
};
const h = (s) => parseInt(createHash("sha1").update(s).digest("hex").slice(0, 8), 16);

function dress(e) {
  const kind = e.style.startsWith("gen-") ? "gen" : (e.type ?? "").toLowerCase() === "painting" ? "painting" : e.style;
  const [frames, m] = DRESS[kind] ?? DRESS.abstract;
  const key = h(e.series);
  return [frames[key % frames.length], m ?? (key % 2 ? 0.09 : 0)];
}

const all = [];
for (const f of ["museum.json", "gen.json"]) all.push(...JSON.parse(await readFile(join(SRC, f), "utf8")));
const out = [];
await mkdir(join(KIT, "assets", "art"), { recursive: true });
for (const e of all) {
  if ((e.tone ?? 1) < DARK || !e.styles?.length) continue;
  if (!e.series) {
    const who = (e.artist ?? "anon").replaceAll(",", " ").split(/\s+/).filter(Boolean).slice(0, 2).join(" ").toLowerCase();
    e.series = `${e.style}-${who}`;
  }
  const [frame, mount] = dress(e);
  await sharp(join(SRC, e.file)).resize(512, 512, { fit: "inside" }).webp({ quality: 82 }).toFile(join(KIT, "assets", "art", `${e.id}.webp`));
  out.push({ id: e.id, w: e.w, h: e.h, style: e.style, series: e.series, styles: e.styles, frame, mount, title: e.title.slice(0, 60) });
}
const lines = out.map((e) => `  ${JSON.stringify(e)},`).join("\n");
await writeFile(join(KIT, "art.js"), `// Wall art by role (#102): fx.model("wall-art", { width, height }) frames one of these, a different one in each room
// of a house (decor.js). Generated by scripts/fetch_art.mjs from the archviz spike's prints (spikes/archviz/made/art:
// museum works in the public domain, CC0, and prints made there): w x h the print's pixels (its shape), \`style\` what
// it is, \`series\` the prints that go together, \`styles\` the house styles it suits (#100), \`frame\` and \`mount\` (a
// fraction of the framed long side; 0: the print runs to the frame) the spike's dressing. The images are
// assets/art/<id>.webp; the photo service frames the full-resolution file of the same id.
export const ART = [
${lines}
];
`);
console.log(`${out.length} prints`);
